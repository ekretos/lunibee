/**
 * Writes lunibee.js.org/src/content/docs/reference/types.mdx: every exported
 * interface and type alias of the `lunibee` package, grouped by package, with
 * its one-line description and a link to its generated API page.
 *
 * Reads the TypeDoc output under docs/api/, so build the docs site first:
 *   cd lunibee.js.org && bun run build && cd .. && bun scripts/docs-types.ts
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const DOCS = join(import.meta.dir, "../lunibee.js.org/src/content/docs");
const KINDS = [
    ["interfaces", "interface"],
    ["type-aliases", "type"],
] as const;

interface Entry {
    name: string;
    kind: string;
    pkg: string;
    summary: string;
    link: string;
}

const entries: Entry[] = [];
for (const [dir, kind] of KINDS) {
    for (const file of (await readdir(join(DOCS, "api", dir))).sort()) {
        if (!file.endsWith(".md")) continue;
        const text = await readFile(join(DOCS, "api", dir, file), "utf8");
        const name = /^title: "?([^"\n]+)"?/m.exec(text)?.[1]?.trim();
        if (!name) continue;
        const pkg = /packages\/([a-z-]+)\/src/.exec(text)?.[1] ?? "other";
        // The first paragraph after the "Defined in" line is the summary.
        const body = text.split(/^Defined in: .*$/m)[1] ?? "";
        const paragraph =
            body
                .split(/\n\s*\n/)
                .map((p) => p.trim())
                .find((p) => p && !p.startsWith("#") && !p.startsWith(">") && !p.startsWith("```")) ?? "";
        const summary = paragraph
            .replace(/\s+/g, " ")
            .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
            .replace(/\|/g, "\\|")
            .replace(/[{}<>]/g, (c) => `&#${c.charCodeAt(0)};`)
            .replace(/^(.{0,180}?[.!?])\s.*$/, "$1");
        entries.push({
            name,
            kind,
            pkg,
            summary,
            link: `/api/${dir}/${name.toLowerCase()}/`,
        });
    }
}

const packages = [...new Set(entries.map((e) => e.pkg))].sort();
let out = `---
title: Types
description: Every type the lunibee package exports, grouped by package, with a link to its full definition.
---

{/* Generated by scripts/docs-types.ts from the TypeDoc output. Do not edit by hand. */}

Every interface and type alias that \`lunibee\` exports, with what it is for. Each name links to its full definition in the generated API reference. The classes and functions that use these types are described on the other reference pages.

${entries.length} types in ${packages.length} packages.

`;
for (const pkg of packages) {
    out += `## \`@lunibee/${pkg}\`\n\n| Type | Kind | Description |\n|---|---|---|\n`;
    for (const e of entries.filter((x) => x.pkg === pkg))
        out += `| [\`${e.name}\`](${e.link}) | ${e.kind} | ${e.summary} |\n`;
    out += "\n";
}
await writeFile(join(DOCS, "reference/types.mdx"), out);
console.log(`Wrote reference/types.mdx: ${entries.length} types.`);
